"""แปลง OpenAPI ของ API เป็น TypeScript types สำหรับ web (AD-12).

ตัวแปลงขนาดเล็กสำหรับ schema ที่ pydantic สร้าง (object, scalar, array, anyOf/null,
const/enum, $ref) — ไม่พึ่ง ``openapi-typescript`` เพราะ peer dependency ไม่รองรับ TypeScript 7.
"""
from __future__ import annotations

import json
import re

HEADER = "// GENERATED by `bmad-studio openapi --ts` from the FastAPI OpenAPI schema. Do not edit.\n"


def _ident(name: str) -> str:
    return re.sub(r"[^0-9A-Za-z_]", "_", name)


def ts_type(schema: dict) -> str:
    if "$ref" in schema:
        return _ident(schema["$ref"].rsplit("/", 1)[-1])
    if "const" in schema:
        return json.dumps(schema["const"], ensure_ascii=False)
    if "enum" in schema:
        return " | ".join(json.dumps(v, ensure_ascii=False) for v in schema["enum"])
    for key in ("anyOf", "oneOf"):
        if key in schema:
            parts = []
            for sub in schema[key]:
                text = ts_type(sub)
                if text not in parts:
                    parts.append(text)
            return " | ".join(parts)
    kind = schema.get("type")
    if isinstance(kind, list):
        return " | ".join(ts_type({**schema, "type": k}) for k in kind)
    if kind == "string":
        return "string"
    if kind in ("integer", "number"):
        return "number"
    if kind == "boolean":
        return "boolean"
    if kind == "null":
        return "null"
    if kind == "array":
        inner = ts_type(schema.get("items", {}))
        return f"Array<{inner}>"
    if kind == "object" or "properties" in schema:
        if "properties" not in schema:
            extra = schema.get("additionalProperties")
            value = ts_type(extra) if isinstance(extra, dict) else "unknown"
            return f"Record<string, {value}>"
        return _object(schema, indent="  ")
    return "unknown"


def _object(schema: dict, indent: str = "") -> str:
    required = set(schema.get("required", []))
    lines = ["{"]
    for name, prop in schema.get("properties", {}).items():
        optional = "" if name in required else "?"
        key = name if re.fullmatch(r"[A-Za-z_$][0-9A-Za-z_$]*", name) else json.dumps(name)
        lines.append(f"{indent}  {key}{optional}: {ts_type(prop)};")
    lines.append(f"{indent}}}")
    return "\n".join(lines)


def render_ts(openapi: dict) -> str:
    schemas = openapi.get("components", {}).get("schemas", {})
    out = [HEADER]
    for name in sorted(schemas):
        schema = schemas[name]
        if schema.get("type") == "object" or "properties" in schema:
            out.append(f"export interface {_ident(name)} {_object(schema)}\n")
        else:
            out.append(f"export type {_ident(name)} = {ts_type(schema)};\n")
    return "\n".join(out)
